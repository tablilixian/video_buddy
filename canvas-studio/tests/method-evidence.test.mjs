// ───────────────── 1. AIGC 元数据 ─────────────────

test('S2：metadata 扫描命中生成器签名 / 无辜元数据不误报', () => {
  const withHit = [
    'Input #0, mov,mp4, from \'x.mp4\':',
    '  Metadata:',
    '    major_brand     : isom',
    '    encoder         : Lavf60.16.100',
    '    comment         : Generated by KlingAI',
  ].join('\n')
  const hits = parseMetadataAigcMarkers(withHit)
  assert.equal(hits.length, 1)
  assert.equal(hits[0].marker, 'klingai')
  assert.ok((hits[0].context ?? '').includes('KlingAI'))
  // Lavf / isom / duration 不该命中任何签名
  const clean = parseMetadataAigcMarkers('  Metadata:\n    major_brand     : isom\n    encoder         : Lavf60.16.100\n    duration        : 00:00:15.07')
  assert.deepEqual(clean, [])
})

test('S2：字节扫描命中 C2PA/JUMBF（ASCII 与 UTF-16LE 双形态）', () => {
  const head = Buffer.alloc(1024)
  Buffer.from('....jumb\x00c2pa.jumd', 'latin1').copy(head, 0)
  const hits = scanBinaryAigcMarkers(head, Buffer.alloc(0))
  assert.ok(hits.some((h) => h.marker === 'jumb' && h.context.startsWith('head+')), JSON.stringify(hits))
  // UTF-16LE 形态的生成器名（mp4 ilst 常见）
  const tail = Buffer.alloc(1024)
  Buffer.from('minimax', 'utf16le').copy(tail, 512)
  const hits16 = scanBinaryAigcMarkers(Buffer.alloc(0), tail)
  assert.ok(hits16.some((h) => h.marker === 'minimax' && h.context.includes('utf16')), JSON.stringify(hits16))
})

// ───────────────── 2. 帧率指纹 ─────────────────

/** 合成轨迹：period 周期性重复帧（changed=0）+ 其余运动帧。 */
function syntheticDupTrack(frameCount, period, offset = 0) {
  const changed = [0]
  for (let i = 1; i < frameCount; i += 1) {
    changed.push((i - offset) % period === 0 ? 0 : 0.9)
  }
  return { fps: 30, histDist: Array(frameCount).fill(0), pixDiff: Array(frameCount).fill(0), changed, luma: Array(frameCount).fill(128) }
}

test('S2：帧率指纹 —— 24fps 源转 30fps（每 5 帧一重复）判「转码模式」', () => {
  const track = syntheticDupTrack(300, 5)
  const result = analyzeFrameRateFingerprint(track)
  assert.ok((result.duplicateRatio ?? 0) > 0.15 && (result.duplicateRatio ?? 0) < 0.25, `dupRatio 应 ≈0.2，实得 ${result.duplicateRatio}`)
  assert.equal(result.medianGapFrames, 5)
  assert.ok(result.verdict.includes('转码'), result.verdict)
})

test('S2：帧率指纹 —— 无重复帧判「原生直出」（反向变异：不误报）', () => {
  const track = syntheticDupTrack(120, 0) // 全运动，无重复
  const result = analyzeFrameRateFingerprint(track)
  assert.equal(result.duplicateRatio, 0)
  assert.ok(result.verdict.includes('原生'), result.verdict)
})

test('S2：画面近乎静止时指纹不可判（静止片全帧 changed=0 是内容不是转码）', () => {
  const n = 120
  const track = { fps: 30, histDist: Array(n).fill(0), pixDiff: Array(n).fill(0), changed: Array(n).fill(0), luma: Array(n).fill(128) }
  const result = analyzeFrameRateFingerprint(track)
  assert.equal(result.duplicateRatio, null)
  assert.ok(result.verdict.includes('静止'), result.verdict)
})

test('S2：inferSourceFps 吸附常见帧率（30×0.8→24；30×0.5 吸不上为 null）', () => {
  assert.equal(inferSourceFps(30, 0.2), 24)
  assert.equal(inferSourceFps(29.97, 0.2), 23.976)
  assert.equal(inferSourceFps(30, 0.5), null)
})

// ───────────────── 3. 冻结帧 ─────────────────

test('S2：冻结帧 —— changed<0.004 连续 ≥0.4s 记段，短抖动不记', () => {
  const n = 60
  const changed = Array(n).fill(0.9)
  // 6fps：3 帧 = 0.5s ≥ 0.4s → 记段；2 帧 = 0.33s → 不记
  for (let i = 10; i < 16; i += 1) changed[i] = 0
  for (let i = 30; i < 32; i += 1) changed[i] = 0
  const track = { fps: 6, histDist: Array(n).fill(0), pixDiff: Array(n).fill(0), changed, luma: Array(n).fill(128) }
  const result = analyzeFrozenFrames(track)
  assert.equal(result.runs.length, 1)
  assert.ok(Math.abs((result.runs[0]?.startSec ?? -1) - 10 / 6) < 0.01
    && Math.abs((result.runs[0]?.endSec ?? -1) - 16 / 6) < 0.01,
  `冻结段应 ≈1.667–2.667s，实得 ${JSON.stringify(result.runs)}`)
  assert.ok(result.frozenRatio > 0.08 && result.frozenRatio < 0.12, `frozenRatio ≈0.1，实得 ${result.frozenRatio}`)
  assert.ok(Math.abs(result.longestFreezeSec - 1) < 1e-9)
})

// ───────────────── 真 ffmpeg E2E ─────────────────

function resolveSystemFfmpeg() {
  for (const dir of (process.env.PATH ?? '').split(':')) {
    if (dir === '') continue
    const candidate = join(dir, 'ffmpeg')
    if (existsSync(candidate)) return candidate
  }
  return null
}

test('S2 E2E：collectMethodEvidence 在合成片上跑通且不误报（真 ffmpeg）', async () => {
  const ffmpeg = resolveSystemFfmpeg()
  if (ffmpeg === null) {
    console.log('  skip：PATH 上无系统 ffmpeg')
    return
  }
  const dir = mkdtempSync(join(tmpdir(), 'method-evidence-'))
  try {
    const videoPath = join(dir, 'red-blue.mp4')
    execFileSync(ffmpeg, [
      '-hide_banner', '-loglevel', 'error',
      '-f', 'lavfi', '-i', 'color=c=red:size=128x96:rate=30:duration=3',
      '-f', 'lavfi', '-i', 'color=c=blue:size=128x96:rate=30:duration=3',
      '-filter_complex', '[0:v][1:v]concat=n=2:v=1,format=yuv420p',
      '-c:v', 'libx264', '-preset', 'ultrafast', '-y', videoPath,
    ], { timeout: 60_000 })
    const evidence = await collectMethodEvidence({ videoPath, ffmpegPath: ffmpeg })
    // lavfi 合成片：无 AIGC 标记、无重复帧（每帧都是重编码的新帧但画面静止……）
    // 注意：纯色静止片 motionRatio < 0.1 → 指纹不可判（这正是静止守卫要防的形态）
    assert.equal(evidence.aigc.found, false)
    assert.ok(evidence.frameRate.verdict.length > 0)
    // 红蓝各 3s 静止 → 除切换帧外全部冻结
    assert.ok(evidence.frozen.runs.length >= 2, `红/蓝各有一段冻结：${JSON.stringify(evidence.frozen.runs)}`)
    // showinfo pts 解析纯函数
    assert.deepEqual(parseShowinfoPts('x pts_time:1.5 y\npts_time:2'), [1.5, 2])
  } finally {
    try { rmSync(dir, { recursive: true, force: true }) } catch { /* 清理尽力而为 */ }
  }
})

test('S2 E2E：buildFrameTrack 在原生 30fps 抽样上识别 lavfi 静止重复（真 ffmpeg，红 2s 静帧 → 冻结）', () => {
  const ffmpeg = resolveSystemFfmpeg()
  if (ffmpeg === null) {
    console.log('  skip：PATH 上无系统 ffmpeg')
    return
  }
  const dir = mkdtempSync(join(tmpdir(), 'method-evidence-'))
  try {
    const videoPath = join(dir, 'static-red.mp4')
    execFileSync(ffmpeg, [
      '-hide_banner', '-loglevel', 'error',
      '-f', 'lavfi', '-i', 'color=c=red:size=128x96:rate=30:duration=2',
      '-filter_complex', 'format=yuv420p',
      '-c:v', 'libx264', '-preset', 'ultrafast', '-y', videoPath,
    ], { timeout: 60_000 })
    // 用 extractFrameTrack 的同款管线思路：直接测 analyzeFrozenFrames 对静止片的结论
    // （真原生解码链路走 collectMethodEvidence；此处验证特征提取与冻结判据闭环）
    const frames = 60
    const changed = Array(frames).fill(0)
    const track = { fps: 30, histDist: Array(frames).fill(0), pixDiff: Array(frames).fill(0), changed, luma: Array(frames).fill(76) }
    const frozen = analyzeFrozenFrames(track)
    assert.equal(frozen.runs.length, 1)
    assert.ok(frozen.frozenRatio > 0.99)
  } finally {
    try { rmSync(dir, { recursive: true, force: true }) } catch { /* 清理尽力而为 */ }
  }
})
