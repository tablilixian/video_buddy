/**
 * 视频理解（`video2vl`）的提示词**单一事实源**（CV-230）。
 *
 * 为什么固化在代码里、而不是让模型自己写：这段模板是**后端同事按 Qwen3-VL 的实际表现调过的**
 * —— 角色设定 + 九项字段清单 + 「直接输出、不要注释」的收口缺一不可（漏掉字段清单，输出会变成
 * 泛泛的剧情复述；漏掉收口，模型会在结果里夹「备注 / 建议 / 下一步」这类噪声，直接污染下游
 * 写 prompt 的输入）。**让模型照抄长模板一定会漂移**，所以：
 *
 * - 工具侧提供 `mode: 'shot-breakdown'` —— 模型只要说「要分镜拆解」，Host 就用这里的模板发请求，
 *   模型**不需要**、也不应该把模板抄进 `prompt`（实测抄写会漏项、会改措辞）；
 * - `references/toolchain.md` 内嵌同一段明文供人阅读，`tests/video-analysis.test.mjs`
 *   断言两处**逐字节一致**（与 `style-tokens.ts` ↔ `look.md` 同一套防漂移做法）；
 * - 常量内容另由测试断言「九项字段 + 收口句」齐备。
 *
 * 纯常量模块：不 import 任何运行时依赖，Host / 测试 / 文档脚本都能安全引用。
 */

/**
 * 视频分析师的**默认系统提示词**（后端同事给出的角色设定）。
 *
 * 工具 `video2vl` 的 `systemPrompt` 缺省即用这一段 —— 让「不说任何额外要求」的一次调用
 * 也落在镜头的语言体系里，而不是让模型拿通用助手的口吻复述剧情。
 */
export const VIDEO_ANALYST_SYSTEM_PROMPT = '你是一名拥有10年以上经验的电影分镜分析设计师，精通类型片视觉叙事，能准确理解好莱坞与独立电影语言下的分镜语法，擅长将镜头细节转化为专业描述，服务于导演或编剧的工作需求。'

/**
 * 「分镜拆解」的**官方推荐用户提示词**（`mode: 'shot-breakdown'` 实际发出的那一份）。
 *
 * 九个字段（出现时间 / 主体画面 / 运镜方式 / 镜头作用 / 运动节奏 / 人物与关键物件 / 景别 / 音效
 * + 切换规则）就是这份模板的全部价值所在，**不要删项、不要改措辞**（改了就与后端同事的实测
 * 调优脱钩）。要换成别的问法时走 `mode: 'free'` 自己写 prompt，别动这一段。
 */
export const VIDEO_SHOT_BREAKDOWN_PROMPT = '接下来我要基于这段视频来进行分镜拆解，请根据视频内容进行分析：识别并列出每一个分镜出现的具体时间点（秒），逐项描述每个分镜的主体画面内容、运镜方式（特写/中景/远景/俯拍/跟拍/环绕/侧移/拉远等）、镜头作用（交代环境/突出情绪/建立悬念/强化动作等）、运动节奏（慢推/快切/手持感等）、人物与关键物件；出现新画面或人物时一律切换分镜说明；在内容明确的情况下，补充该分镜对应的景别与音效（听不出则写「未知」）。要求：直接输出分析结果，不要任何注释、备注、说明或建议。'

/**
 * `mode: 'shot-breakdown'` 时，把模型额外给的关注点补在模板末尾的句子前缀。
 *
 * 模板本身要求「不要注释」—— 但**用户/模型的额外关注点不是注释，是提问的一部分**，
 * 所以允许追加（另起一行、单句、不加小节标题），既不破坏模板的收口语义，也不丢掉意图。
 */
export const VIDEO_SHOT_BREAKDOWN_FOCUS_PREFIX = '另外请额外关注：'
